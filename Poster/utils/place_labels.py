# utils/place_labels.py
"""
Подписи площадок в списках и результатах поиска (Poster 2.0 U1a).

Город необязателен в данных: у старых площадок его нет (`city IS NULL`),
поэтому подпись «Название · Город» строится в одном месте — и в справочнике
«Места», и в визарде анонса. Дублировать правило по обработчикам нельзя:
иначе один экран покажет висячий разделитель или `None`.
"""

from __future__ import annotations


def place_title(name: str, city: str | None) -> str:
    """
    «Название · Город» для строк списка и подписей кнопок.

    Без города (или при пустой строке) остаётся просто название — без
    висячего разделителя и без «None».
    """
    if city and str(city).strip():
        return f"{name} · {city}"
    return name
