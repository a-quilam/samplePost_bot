def _canonical(text: str) -> str:
    """
    Канонизация фразы словаря: регистр → нижний, ё → е, тире/дефис/№ и
    прочая пунктуация → пробел, множественные пробелы схлопываются.
    «гуси-лебеди», «гуси лебеди», «ГУСИ—ЛЕБЕДИ» → «гуси лебеди».
    """
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[—–\-№]", " ", text)
    text = re.sub(r"[^\w\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


# Каноническая карта: ключ — фраза из токенов, значение — число.
# Отсечены: (1) чисто цифровые ключи («38» оригинала) — они бесполезны
# и совпали бы с обычными числами пользователя; (2) «8 марта» — нативный
# разбор даты «8 марта» важнее пасхалки, подмена на «8» сломала бы его.
CANONICAL_NUMBERS: dict[str, int] = {
    _canonical(key): value
    for key, value in LOTTO_NUMBERS.items()
    if not _canonical(key).isdigit() and _canonical(key) != "8 марта"
}

# Самые длинные фразы первыми — защита от «двадцать» внутри «двадцать пять»
_SORTED_KEYS = sorted(CANONICAL_NUMBERS, key=lambda k: (-len(k.split()), -len(k)))

# Границы токенов: фраза не должна совпадать внутри более длинного слова
# («палатка» не содержит «палата», «золотой» не содержит «золото»).
_LOTTO_RE = re.compile(
    r"(?<![a-zа-яё0-9])(" + "|".join(map(re.escape, _SORTED_KEYS)) + r")"
    r"(?![a-zа-яё0-9])"
)


def substitute_lotto(text: str) -> str:
    """
    Заменяет лото-фразы их числами в контекстной строке даты/времени.

    Нормализует регистр и ё/е, дефисы и тире между буквами → пробел
    («гуси-лебеди» = «гуси лебеди»), дефис МЕЖДУ ЦИФРАМИ сохраняется
    (даты «17-11» не ломаются). Обычные числа и неизвестные слова
    остаются как есть; пасхалка не ломает стандартный парсер.
    """
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[—–№]", " ", text)
    text = re.sub(r"(?<!\d)-|-(?!\d)", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return _LOTTO_RE.sub(lambda m: str(CANONICAL_NUMBERS[m.group(0)]), text)
