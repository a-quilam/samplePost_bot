# utils/ui_humor.py
"""
Poster 2.0 S3: хук короткой шутки для **служебного** экрана.

Границы S3: здесь только фиксированный набор фраз и чистая функция выбора.
Вероятностный модуль редких вариаций (≈1%, детерминированный ключ,
глобальное отключение) — S5; сюда он подключится без изменения вызывающего
кода.

Шутка допустима **только** в нижнем служебном сообщении и только когда
анонс пуст. В готовый анонс (live-блок и `publication_text`) она попадать не
должна никогда — за это отвечает вызывающий слой: рендер поста сюда не
обращается.
"""

from __future__ import annotations

# Фиксированный набор: без LLM, без сети, без случайности в S3. Одна и та же
# фраза на пустом анонсе — «постоянная», как требует план S3 п.11.
EMPTY_ANNOUNCEMENT_JOKES: tuple[str, ...] = (
    "Анонс пока пуст — как сцена до саундчека. Заполните поле или отправьте фото.",
    "Пусто, но интригующе. Добавьте хотя бы одно слово — и это уже анонс.",
    "Пока это самый лаконичный анонс в истории. Разбавим?",
)


def empty_announcement_joke() -> str:
    """
    Короткая шутка для служебного экрана пустого анонса.

    S3: всегда первая фраза набора (стабильно при перерисовке). S5 заменит
    выбор на детерминированный `pick_variant(key)` с ≈1% показов, не меняя
    контракт этой функции.
    """
    return EMPTY_ANNOUNCEMENT_JOKES[0]


def humor_enabled() -> bool:
    """
    Включён ли юмор.

    В S3 настройки нет: шутка для пустого анонса показывается штатно
    (спека §5.6 — «показ обязателен, а не вероятностный»). S5 добавит
    глобальный флаг, и эта функция начнёт читать его вместо константы.
    """
    return True


def get_humor_line(*, announcement_is_empty: bool) -> str | None:
    """
    Строка шутки для нижнего служебного экрана — или None.

    Единственная точка вызова из UI: решает только «пусто/не пусто» и
    включён ли юмор. В live-блок и в отправленный анонс эта функция не
    вызывается, поэтому шутка физически не может попасть в пост.
    """
    if not announcement_is_empty:
        return None
    if not humor_enabled():
        return None
    return empty_announcement_joke()
